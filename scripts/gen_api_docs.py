"""Generate docs/API.md and docs/openapi.json from the running application's own route table.

Each endpoint lists: access class (from tests/test_routes.py INVENTORY, which CI enforces), request
schema, success response, and the rate-limit bucket(s) it uses (static scan of the handler source).
"""
from __future__ import annotations

import inspect
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("ENV", "development")

from app.main import create_app  # noqa: E402
from app.ratelimit import BUCKETS, FAIL_CLOSED  # noqa: E402
from tests.test_routes import INVENTORY, _flatten  # noqa: E402

app = create_app()
spec = app.openapi()
(ROOT / "docs" / "openapi.json").write_text(json.dumps(spec, indent=1, sort_keys=True))

ACCESS = {"public": "none", "optional-auth": "optional", "user": "**required**",
          "admin": "**staff + MFA step-up**"}
handlers = {}
for r in _flatten(app.router.routes):
    for m in getattr(r, "methods", None) or ["WS"]:
        handlers[(m, r.path)] = getattr(r, "endpoint", None)


def buckets(fn) -> str:
    if fn is None:
        return ""
    try:
        src = inspect.getsource(fn)
    except OSError:
        return ""
    found = re.findall(r'(?:enforce_limit|rate_limit|_limit)\(\s*(?:p,\s*)?"(\w+)"', src)
    if "read_limit(" in src:
        found.append("read")
    if 'staff("' in src:
        found.append("admin")
    if "principal" in src:
        found.insert(0, "api")
    return ", ".join(f"`{b}`" + (" (fail-closed)" if b in FAIL_CLOSED else "") for b in dict.fromkeys(found))


def schema_ref(op, where):
    try:
        if where == "req":
            s = op["requestBody"]["content"]["application/json"]["schema"]
        else:
            ok = next(v for k, v in op["responses"].items() if k.startswith("2"))
            s = ok["content"]["application/json"]["schema"]
        return "`" + s["$ref"].split("/")[-1] + "`" if "$ref" in s else "JSON"
    except (KeyError, StopIteration):
        return "—"


lines = ["# Bastion API reference", "",
         "Generated by `scripts/gen_api_docs.py` from the application itself; do not edit by hand.",
         "Machine-readable spec: [`openapi.json`](openapi.json).", "",
         "## Conventions", "",
         "* Base paths: user API `/api/v1`, administrative API `/admin/api/v1` (separate router, stricter controls).",
         "* Auth: `__Host-bastion_sid` session cookie (browsers) **or** `Authorization: Bearer bst_…` personal access "
         "token (scopes `read`/`write`/`dm`). Sending both is rejected. Account-security and admin endpoints refuse tokens.",
         "* CSRF: cookie-authenticated `POST/PUT/PATCH/DELETE` require `X-CSRF-Token` (from `GET /api/v1/auth/session`) "
         "and a same-origin `Origin`.",
         "* Bodies: `application/json` only (except raw media upload), ≤ 64 KiB, strict parsing (duplicate keys, NaN, "
         "NUL and nesting > 32 rejected), unknown fields rejected (422).",
         "* Errors: `{\"error\": {\"code\", \"message\", \"request_id\", \"details?\"}}`. Never stack traces. Objects the "
         "caller may not see return **404** (no existence oracle).",
         "* Pagination: opaque `cursor`, `limit` 1–50 (default 20); response `next_cursor`.",
         "* Rate limits: `429` + `Retry-After`. Buckets are adaptive by trust tier (anon/new/basic/established).", "",
         "## Endpoints", "",
         "| Method | Path | Auth | Request | Response | Rate-limit buckets |", "|---|---|---|---|---|---|"]
for (m, p), cls in sorted(INVENTORY.items(), key=lambda x: (x[0][1], x[0][0])):
    op = spec["paths"].get(p, {}).get(m.lower(), {})
    lines.append(f"| {m} | `{p}` | {ACCESS[cls]} | {schema_ref(op, 'req') if m not in ('GET', 'DELETE', 'WS') else '—'} "
                 f"| {schema_ref(op, 'res') if m != 'WS' else 'event stream'} | {buckets(handlers.get((m, p)))} |")
lines += ["", "## Rate-limit buckets", "", "| Bucket | anon | new | basic | established | window | on backend failure |",
          "|---|---|---|---|---|---|---|"]
for b, t in BUCKETS.items():
    def v(tier, t=t):
        x = t.get(tier) or t.get("*")
        return str(x[0]) if x else "—"
    win = (t.get("*") or next(iter(t.values())))[1]
    lines.append(f"| `{b}` | {v('anon')} | {v('new')} | {v('basic')} | {v('established')} | {win}s | "
                 f"{'**fail closed (503)**' if b in FAIL_CLOSED else 'per-process fallback'} |")
lines += ["", "## Request schemas", ""]
for name, s in sorted(spec.get("components", {}).get("schemas", {}).items()):
    if not name.endswith("In"):
        continue
    lines.append(f"### `{name}`\n")
    lines.append("| Field | Type | Constraints |\n|---|---|---|")
    req = set(s.get("required", []))
    for f, d in s.get("properties", {}).items():
        typ = d.get("type") or ("/".join(x.get("type", x.get("$ref", "").split("/")[-1]) for x in d.get("anyOf", [])) or
                                d.get("$ref", "").split("/")[-1])
        cons = ", ".join(f"{k}={d[k]}" for k in ("minLength", "maxLength", "minimum", "maximum", "pattern", "enum",
                                                 "maxItems") if k in d)
        lines.append(f"| `{f}`{' *' if f in req else ''} | {typ} | {cons} |")
    lines.append("")
lines += ["## WebSocket protocol (`/api/v1/ws`)", "",
          "Client → server frames (anything else closes with 1008): `{\"type\":\"ping\"}`, "
          "`{\"type\":\"subscribe\",\"topic\":\"conversation:<uuid>\"}`, `{\"type\":\"unsubscribe\",...}`, "
          "`{\"type\":\"typing\",\"conversation_id\":\"<uuid>\"}`.", "",
          "Server → client: `hello`, `pong`, `subscribed`, `error`, `notification`, `message`, `message_deleted`, "
          "`typing`. Close codes: 1003 binary, 1008 policy, 1009 too big, 1013 slow consumer, 4001 session revoked, "
          "4003 account disabled, 4429 rate/connection limit.", ""]
(ROOT / "docs" / "API.md").write_text("\n".join(lines) + "\n")
print(f"wrote docs/API.md ({len(INVENTORY)} endpoints) and docs/openapi.json")
