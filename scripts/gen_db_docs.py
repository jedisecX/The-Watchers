"""Generate docs/DATABASE.md from the SQLAlchemy metadata (which `alembic check` proves equals the migrations)."""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("ENV", "development")
from sqlalchemy import CheckConstraint, ForeignKeyConstraint, UniqueConstraint  # noqa: E402

from app.models import Base  # noqa: E402

GRANTS = {
    "audit_log": "app: SELECT, INSERT only (+ trigger blocks UPDATE/DELETE/TRUNCATE for everyone)",
    "media": "app: DML; **worker: SELECT + UPDATE(state, variants, width, height, duration_ms, error_code, attempts, "
             "claimed_at, processed_at, quarantine_key)**",
}
out = ["# Database schema", "",
       "Generated by `scripts/gen_db_docs.py` from `backend/app/models.py`. CI runs `alembic check` to prove the models",
       "and migrations are identical, and runs every migration up → down → up.", "",
       "## Roles (least privilege)", "",
       "| Role | Used by | Privileges |", "|---|---|---|",
       "| `bastion_migrator` | one-shot migrate job | Owns the schema (DDL). Never used at runtime. |",
       "| `bastion_app` | API, mailer | DML on application tables; `audit_log` INSERT/SELECT only; no DDL |",
       "| `bastion_worker` | media worker | `media`: SELECT + UPDATE on processing columns only. Nothing else. |",
       "| `postgres` | bootstrap only | Superuser; creds kept offline after init |", "",
       "Session settings on every app connection: `statement_timeout=5s`, `idle_in_transaction_session_timeout=15s`.", "",
       "## Conventions", "",
       "* Primary keys: random UUIDv4 (non-enumerable), except `audit_log.seq` (ordering of the hash chain).",
       "* Enumerations: `varchar` + `CHECK (col IN (...))`.",
       "* Relationship tables use composite PKs, so duplicates (double-like, double-follow) are impossible.",
       "* Self-relations are forbidden by `CHECK` (follow/block/mute yourself, notify yourself).",
       "* Counters carry `CHECK (>= 0)` and change only on real inserts/deletes.",
       "* Secrets: session/API/verification tokens are SHA-256 hashes; TOTP seeds are AES-256-GCM with the user id as AAD.",
       "* Soft delete: posts (`deleted_at` = author delete with body erased, `removed_at` = moderation), users "
       "(`deleted_at`, `purge_after` = hard delete after 30 days, FK cascades remove owned rows).", "",
       "## Tables", ""]
for t in Base.metadata.sorted_tables:
    out.append(f"### `{t.name}`")
    if t.name in GRANTS:
        out.append(f"\nPrivileges: {GRANTS[t.name]}\n")
    out.append("\n| Column | Type | Null | Default |\n|---|---|---|---|")
    for c in t.columns:
        default = c.server_default.arg if c.server_default is not None and hasattr(c.server_default, "arg") else ""
        default = getattr(default, "text", default)
        if c.computed is not None:
            default = f"GENERATED: {c.computed.sqltext}"
        pk = " **PK**" if c.primary_key else ""
        out.append(f"| `{c.name}`{pk} | {c.type} | {'yes' if c.nullable else 'no'} | {str(default)[:60]} |")
    cons = []
    for k in t.constraints:
        if isinstance(k, ForeignKeyConstraint):
            cols = ", ".join(c.name for c in k.columns)
            ref = k.elements[0].target_fullname.split(".")[0]
            cons.append(f"FK ({cols}) → `{ref}` ON DELETE {k.ondelete or 'NO ACTION'}")
        elif isinstance(k, UniqueConstraint):
            cons.append(f"UNIQUE ({', '.join(c.name for c in k.columns)})")
        elif isinstance(k, CheckConstraint) and k.name and not str(k.name).startswith("_"):
            cons.append(f"CHECK `{k.name}`: `{k.sqltext}`")
    for c in t.columns:
        if c.unique:
            cons.append(f"UNIQUE ({c.name})")
    for i in t.indexes:
        extra = []
        if i.unique:
            extra.append("unique")
        if i.dialect_options["postgresql"].get("where") is not None:
            extra.append(f"partial: {i.dialect_options['postgresql']['where']}")
        if i.dialect_options["postgresql"].get("using"):
            extra.append(i.dialect_options["postgresql"]["using"])
        if i.dialect_options["postgresql"].get("nulls_not_distinct"):
            extra.append("NULLS NOT DISTINCT")
        cons.append(f"INDEX `{i.name}` ({', '.join(str(e.name) for e in i.expressions)})"
                    + (f" [{'; '.join(extra)}]" if extra else ""))
    if cons:
        out.append("\n" + "\n".join(f"* {x}" for x in cons))
    out.append("")
(ROOT / "docs" / "DATABASE.md").write_text("\n".join(out) + "\n")
print(f"wrote docs/DATABASE.md ({len(Base.metadata.sorted_tables)} tables)")
